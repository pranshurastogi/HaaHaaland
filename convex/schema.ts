import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";
export default defineSchema({
  users: defineTable({
    email: v.string(),
    createdAt: v.number(),
    activatedAt: v.optional(v.number()),
  }).index("by_email", ["email"]),
  anonymousSessions: defineTable({
    sessionId: v.string(),
    referralCode: v.optional(v.string()),
    createdAt: v.number(),
    lastSeenAt: v.number(),
  }).index("by_session", ["sessionId"]),
  generatedCards: defineTable({
    publicId: v.string(),
    sessionId: v.string(),
    handle: v.string(),
    archetypeId: v.string(),
    card: v.any(),
    researchConfidence: v.number(),
    model: v.string(),
    promptVersion: v.string(),
    taxonomyVersion: v.string(),
    durationMs: v.number(),
    retryCount: v.number(),
    viewedAt: v.optional(v.number()),
    emailSavedAt: v.optional(v.number()),
    createdAt: v.number(),
  })
    .index("by_public_id", ["publicId"])
    .index("by_handle", ["handle"]),
  researchSnapshots: defineTable({
    handle: v.string(),
    queryVersion: v.string(),
    sources: v.array(v.string()),
    excerpts: v.array(v.string()),
    confidence: v.number(),
    providerRequestId: v.optional(v.string()),
    errorCategory: v.optional(v.string()),
    retrievedAt: v.number(),
    expiresAt: v.number(),
  }).index("by_handle_version", ["handle", "queryVersion"]),
  referrals: defineTable({
    referrerCardId: v.string(),
    referredSessionId: v.string(),
    convertedAt: v.optional(v.number()),
    createdAt: v.number(),
  }).index("by_referrer", ["referrerCardId"]),
  challenges: defineTable({
    code: v.string(),
    sourceCardId: v.string(),
    friendHandle: v.optional(v.string()),
    acceptedSessionId: v.optional(v.string()),
    createdAt: v.number(),
  }).index("by_code", ["code"]),
  credits: defineTable({
    userId: v.id("users"),
    balance: v.number(),
    reason: v.string(),
    createdAt: v.number(),
  }).index("by_user", ["userId"]),
  leaderboard: defineTable({
    cardId: v.string(),
    handle: v.string(),
    aura: v.number(),
    archetypeId: v.string(),
    eligible: v.boolean(),
    updatedAt: v.number(),
  }).index("by_aura", ["eligible", "aura"]),
  shareEvents: defineTable({
    cardId: v.string(),
    channel: v.string(),
    sessionId: v.string(),
    createdAt: v.number(),
  }).index("by_card", ["cardId"]),
  audioStatus: defineTable({
    cardId: v.string(),
    status: v.string(),
    storageUrl: v.optional(v.string()),
    errorCategory: v.optional(v.string()),
    updatedAt: v.number(),
  }).index("by_card", ["cardId"]),
  payments: defineTable({
    providerId: v.string(),
    userId: v.optional(v.id("users")),
    status: v.string(),
    amount: v.number(),
    currency: v.string(),
    createdAt: v.number(),
  }).index("by_provider_id", ["providerId"]),
  auditEvents: defineTable({
    action: v.string(),
    actorType: v.string(),
    targetId: v.optional(v.string()),
    requestId: v.optional(v.string()),
    metadata: v.optional(v.any()),
    createdAt: v.number(),
  }).index("by_action", ["action"]),
  generationStatus: defineTable({
    publicId: v.string(),
    status: v.string(),
    step: v.string(),
    errorCategory: v.optional(v.string()),
    updatedAt: v.number(),
  }).index("by_public_id", ["publicId"]),
});
